const OFFICIAL_RE =
  /庁|政府|市政府|县政府|県庁|ministry|government|official app|大学|銀行|bank$|郵便局|digital agency|デジタル庁|furyu|zenrin|sega corporation|square enix|bundesamt|bundesagentur|taxation|勞動部|劳动部|fujifilm|1&1 mail/i;

const OFFICIAL_APP_RE =
  /mygov|myid|ausweis|identité|identite|mynaportal|マイナポータル|デジタル認証|自然人憑證|gov\.uk|one login|france identit|icn smartpass|mobile identification|pokémon home|pokemon home|ピクトリンク|プリクラ|職安卡|nina\b/i;

export function isBigOrOfficialPublisher(artistName: string): boolean {
  const name = artistName.trim();
  if (!name) return false;
  if (OFFICIAL_RE.test(name)) return true;
  const lower = ` ${name.toLowerCase()} `;
  return BIG_PUBLISHER_NEEDLES.some((needle) => lower.includes(needle));
}

export function isOfficialOrBigApp(name: string, artistName: string): boolean {
  return isBigOrOfficialPublisher(artistName) || OFFICIAL_APP_RE.test(name);
}
